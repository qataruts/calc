/**
 * **درجاتُ السلّم: شرائحُ الرحلة بترتيبها — مشتقّةٌ من `sections()` لا مكتوبة.**
 *
 * والشريحةُ **مرحلةٌ وما يتلوها من أقسامٍ حتى المرحلة التالية**، فهي وحدةُ الامتحان
 * والفتح معاً. والحدّان مرسومان هنا لا في موضعٍ آخر فيُقرآن حيث يعملان:
 *   • **البوّابةُ التي لم تُجتز تقطع السلّم** — «تُجتاز بنفسها»؛ وإن كان الطفلُ قد
 *     عبَرها مضى السلّمُ إلى ما بعدها. **والمجتازةُ تُتخطّى ولا تُضمّ** إلى شريحة:
 *     لا يُفتح ما يُجتاز بنفسه.
 *   • **وقسمٌ ليس مرحلةً ولا بوّابةً يلحق بشريحة ما قبله** — فقسمٌ يُوضَع بين مرحلتين
 *     غداً يدخل شريحتَه **يومَ يُوضَع** بلا سطرٍ يُعدَّل.
 *
 * **والقاعدةُ دالّةٌ خالصة** تُحقَن بالأقسام وبمن يعرف المجتازَ ورؤوسَ الشرائح، فيمتحنها
 * حارسُها **بأقسامٍ مصنوعة**: بوّابةٌ بين مرحلتين تقصُر السلّمَ، ومجتازةٌ لا تقصُره،
 * وقسمٌ بينهما ينضمّ إلى شريحته. ولولا الحقنُ لكان الحدّان **صامتين** في رحلة اليوم
 * (لا قسمَ بين المراحل) — والحدُّ الصامت لا يُعرَف صحيحاً من فاسد.
 *
 * @param {object[]} sections أقسامُ الرحلة بترتيبها (`progress.journey()`)
 * @param {(section) => boolean} crossed هل اجتاز هذا القسمَ (للبوّابات)؟
 * @param {Set<string>} heads معرّفاتُ الأقسام التي تبدأ شريحةً (المراحلُ)
 */
export function rungsOf(sections, { crossed, heads }) {
  const parts = [];
  for (const section of sections) {
    if (section.kind === 'gate') {
      if (crossed(section)) continue;
      break;
    }
    if (heads.has(section.id)) parts.push([section]);
    else if (parts.length) parts[parts.length - 1].push(section);
  }
  return parts.map((slice) => ({
    id: slice[0].id,
    title: slice[0].title,
    sections: slice,
    nodes: slice.flatMap((section) => section.nodes || []),
  }));
}

export function rungs() {
  const heads = new Set(STAGES.map((stage) => stage.id));
  return rungsOf(progress.journey(), {
    crossed: (section) => (section.nodes || []).every((node) => progress.isDone(node.id)),
    heads,
  });
}

/**
 * موضعُ الاستئناف: أوّلُ درجةٍ لم تكتمل عقدُها بعد — **«من آخر حدّ»**. فالإعادةُ لا
 * تُعيد امتحانَ ما فُتح، ولا حاجةَ إلى سجلٍّ ثانٍ يقول أين وقف: النجومُ تقوله.
 * (وتعود بطول القائمة إن لم يبق شيء — أي: لا امتحانَ له.)
 */
export function startRung(list = rungs()) {
  const at = list.findIndex((rung) => rung.nodes.some((node) => !progress.isDone(node.id)));
  return at < 0 ? list.length : at;
}

// ————— مادّةُ الدرجة: مفاتيحُ عقدها لا قائمةٌ تُكتب —————

/**
 * محطاتُ الشريحة **التي تُقاس** — وهي التي تعلن مفاتيحَ ليتنر في المنهج.
 * وما سواها **يُعفى بإعفائه المكتوب هناك** (`exempt` في `curriculum.js`: محطةُ
 * التعارف على الأرقام المغربية — عرضٌ بلا سؤالٍ ولا خطأ). ويحرس الفاحصُ ألّا تكون
 * محطةٌ بلا مفاتيحَ وبلا سببٍ مكتوب، فلا يمرّ نوعٌ جديد صامتاً **فيُفتح بامتحانٍ لم يمسّه**.
 */
export const measuredNodes = (rung) => rung.nodes.filter((node) => (node.skills || []).length);

/** وما يُفتح تبعاً ولا يُقاس — لكلٍّ سببُه المكتوب في المنهج. */
export const exemptNodes = (rung) => rung.nodes.filter((node) => !(node.skills || []).length);

/** مفاتيحُ الشريحة كلُّها بلا تكرار — **من عقدها** لا من قائمةٍ تُكتب. */
export function rungKeys(rung) {
  return [...new Set(measuredNodes(rung).flatMap((node) => node.skills))];
}

/**
 * **المفاتيحُ المضمونة**: `PER_STATION` من كل محطةٍ مقيسة في الشريحة، تتقدّم في `due`
 * فلا يبتلعها الخلط. **ومحطةٌ يغطّيها مفتاحٌ اختير قبلها لا تطلب ثانياً** — فمفتاحُ
 * ليتنر وحدةُ القياس، ومن أُثبت مفتاحُه أُثبت في كل محطةٍ تدرّسه. وبذلك تبقى التغطيةُ
 * الكاملةُ دون سقف الجلوس (القيد ٥) في مراحل الرحلة كلِّها.
 */
export function stationKeys(rung, rnd = Math.random) {
  const out = [];
  for (const node of measuredNodes(rung)) {
    const own = node.skills;
    if (out.some((key) => own.includes(key))) continue;
    for (let i = 0; i < Math.min(PER_STATION, own.length); i++) {
      const fresh = own.filter((key) => !out.includes(key));
      if (!fresh.length) break;
      out.push(pick(fresh, rnd));
    }
  }
  return out;
}

/**
 * حجمُ عيّنة الدرجة: `SAMPLE` أدنى، **وتغطيتُها إن زادت عليها**، ولا يتجاوز `CAP`.
 * فلا تُفتح محطةٌ لم تُمَسّ (القيد ٢)، ولا يُطلَب جلوسٌ أثقلُ ممّا في الرحلة (القيد ٥).
 * وشريحةٌ تحتاج أكثرَ من السقف **تُحمِّر حارسَها** — فلا تُختصَر تغطيتُها في الظلّ.
 */
export const sizeFor = (cover) => Math.min(CAP, Math.max(SAMPLE, cover.length));

/**
 * تمارينُ درجةٍ واحدة — **بمُنشئات المراجعة والبوّابة نفسِها** (`sessionItems`)، فكلُّ
 * ما تنطقه له ملفٌّ مولَّد أصلاً و**صفرُ شكلِ تمرينٍ جديد** بالبناء لا بالوعد.
 *
 * ومادّتُها حصّتان: **المفاتيحُ المضمونة أوّلاً** فلا تُفتح محطةٌ لم تُمَسّ، ثم بقيةُ
 * مفاتيح الشريحة مخلوطةً تُكمل العدد. **ثم تُعاد مفاتيحُها مخلوطةً ثالثةً**: شريحةٌ
 * مفاتيحُها أقلُّ من العيّنة (المرحلةُ ١١ مفتاحٌ واحد) تُسأل عنه مراراً بجولاتٍ مولَّدةٍ
 * جديدة — **وهو أصدقُ من امتحانٍ من سؤالٍ واحد يُفتح به ثلاثُ محطات**. **ولا تُكمَّل
 * من خارج الشريحة**: حوضُ التنويع يُمرَّر فارغاً، فلا يُحكَم على مرحلةٍ بخطأٍ في مادّةٍ
 * ليست منها — والعيّنةُ لا تتجاوز ما تملكه الشريحةُ من تمارينَ متمايزة، فتقصُر عن
 * `SAMPLE` حيث تقصُر مادّتُها (وحارسُها يطبع طولَ كلِّ درجةٍ فلا يقع قصرٌ صامت).
 *
 * **وهنا تُشدّ مسطرةُ الامتحان الواحدة** (القيد ٨): البناءُ كلُّه داخل `duringExam`،
 * وفيه تُقرأ مقاديرُ الصعوبة كلُّها — سعةُ حوض الخيارات في مُنشئات المراجعة، وحجمُ
 * العيّنة (وهو `sizeFor` هنا لا جرعةُ وليّ الأمر)، والتلقينُ الذي لا تعرفه هذه الشاشة
 * أصلاً. **ومقابضُ الراحة تسري في الحالين** لأنّها لا تُقرأ هنا: سرعةُ الصوت عند
 * التشغيل، والهدوءُ صنفٌ على الجذر، وفاصلُ العدّ عند العدّ، وموعدُ ليتنر عند تسجيل
 * المحاولة — كلُّها بعد انقضاء هذا النطاق.
 */
export function rungItems(index, rnd = Math.random) {
  const rung = rungs()[index];
  if (!rung) return [];
  const cover = stationKeys(rung, rnd);
  const keys = rungKeys(rung);
  const due = [
    ...cover,
    ...shuffle(keys.filter((key) => !cover.includes(key)), rnd),
    ...shuffle(keys, rnd),
  ].map((key) => progress.parseSkillKey(key));
  return duringExam(() => sessionItems(due, sizeFor(cover), rnd, []));
}

// ————— الفتح: نجمةٌ تفكّ القفل ولا تدّعي إتقاناً —————

/**
 * ما لا يُفتَح بحال — **مكتوبٌ هنا وإن لم تقع البوّابةُ في شريحةٍ اليوم**: هو الذي يبقى
 * صحيحاً حين تتبدّل الرحلة، والحارسُ يقرؤه لا يقرأ حالَ اليوم.
 */
const NEVER_OPENED = new Set(['gate']);

export function openableNodes(rung) {
  return rung.nodes.filter((node) => !NEVER_OPENED.has(node.type)).map((node) => node.id);
}

/**
 * **فتحُ شريحةٍ اجتازها**: نجمةٌ واحدة لكل عقدةٍ **لم يكسب فيها شيئاً** — فلا تُنقَص
 * نجمةٌ كسبها بلعبه (`setStars` لا تخفض أصلاً، والشرطُ هنا ليُحصى ما فُتح فعلاً).
 * **ولا يُعلَّم معرّفٌ لا موضعَ له في الرحلة.**
 * @returns {number} عددُ العقد التي فُتحت فعلاً
 */
export function openRung(rung) {
  let count = 0;
  for (const id of openableNodes(rung)) {
    if (!progress.findNode(id) || progress.getStars(id) > 0) continue;
    if (progress.setStars(id, PLACEMENT_STARS)) count++;
  }
  return count;
}

