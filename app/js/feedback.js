//
// ————— منقولٌ من «اِقْرَأْ» بالتزامٍ مبصوم (`SEED.md §٦`) ومكيَّفٌ بنصوصنا —————
//
// **وحدةٌ مستقلة عن `parent.js` عمداً — درسُ ميدان اقرأ**: هناك يمنع حارسُ الخصوصية
// أيَّ `https://` في وحدةٍ يمرّ بها صوتُ الطفل، ولوحةُ وليّ الأمر تحمل «تسجيلات
// طفلي» — فدُفع ثمنُ الخلط أحمرَ منشوراً. **وعندنا لا صوتَ طفلٍ ولا قلمَه أصلاً**،
// فالفصلُ هنا ليس رفعَ تعارض: هو **حصانةٌ بنيوية لِما قد يُستجدّ** — يوم يدخل
// «اِحْسِبْ» ما يخصّ الطفل يجد العنوانَ الخارجيَّ ساكناً في وحدةٍ لا يمرّ بها.
//
// ولا يعرف هذا الملفُّ الشبكةَ ولا التقدّمَ ولا السجلّ: رابطا `<a>` يُفتحان بنقرة
// الراشد ولا يُجلَبان، وسياقُهما اسمُ التطبيق وقشرتُه فقط — **لا شيءَ من بيانات
// الطفل أبداً** (لا نجومَ ولا مهاراتٍ ولا دقائق)، والمرسِل يرى نصَّه كاملاً في
// تطبيقه قبل الإرسال.

import { h } from './ui.js';

/** واتساب العائلة وبريدُها المرجع — القناتان المعتمدتان (بلاغ العائلة
 *  `2026-08-15-owner-decisions-family-structure` §٥)، ولا ثالثةَ لهما. */
const WHATSAPP = '97433882806';
const EMAIL = 'info@mishkat.qa';
const SUBJECT = 'بلاغ من تطبيق اِحْسِبْ';

/** **«بلِّغنا»**: بابُ الجمهور لكل خطأٍ أو مقترح — من لوحة وليّ الأمر وحدَها (فعلُ
 *  راشدٍ متعمَّد خلف بوابتها الحسابية، ولا زرَّ في شاشة طفل)، رابطا واتساب وبريدٍ
 *  **مملوءان بسطر سياق** يجعل البلاغ قابلاً للعمل: اسمُ التطبيق ونسخةُ قشرته —
 *  **والقشرةُ تُسأل ولا تُكتب بيد** (سنّةُ سطر النسخة في قسم النسخة الاحتياطية). */
export function feedbackSection() {
  let shell = '';

  const context = () => `بلاغ من تطبيق اِحْسِبْ${shell ? ` (قشرة ${shell})` : ''}:\n`;

  const wa = h('a', { class: 'btn', target: '_blank', rel: 'noopener' }, 'عبر واتساب');
  const mail = h('a', { class: 'btn' }, 'عبر البريد');

  const arm = () => {
    const text = `${context()}اكتب ملاحظتك هنا — وأرفق لقطة شاشة إن أمكن.`;
    wa.href = `https://wa.me/${WHATSAPP}?text=${encodeURIComponent(text)}`;
    mail.href = `mailto:${EMAIL}?subject=${encodeURIComponent(SUBJECT)}&body=${encodeURIComponent(text)}`;
  };
  arm();                                  // يعمل الرابطان بلا قشرةٍ أصلاً (بلا سياق نسخة)

  // النسخةُ تُسأل من عامل الخدمة نفسِه — فإن وصلت دخل رقمُها السياق. ولا يتعلّق
  // عملُ البابِ بجوابه: بابٌ ينتظر رسالةً قد لا تأتي بابٌ لا يُفتح.
  navigator.serviceWorker?.addEventListener?.('message', (e) => {
    if (e.data?.type !== 'version' || !e.data.version) return;
    shell = e.data.version;
    arm();
  });
  navigator.serviceWorker?.controller?.postMessage({ type: 'version' });

  return h('div', {},
    h('p', { class: 'hint' },
      'وجدتَ خطأً؟ عندك اقتراح؟ رسالتُك تصلنا مباشرة — وتُفتح في تطبيقك فترى'
      + ' نصَّها قبل إرسالها، ولا يُرفَق معها شيءٌ من بيانات طفلك.'),
    h('div', { class: 'row', css: { 'justify-content': 'flex-start' } }, wa, mail),
  );
}
