/** تشغيلُ الوضع كلِّه أو إطفاؤه (والإطفاء يردّ السلوكَ القائم بلا فقد اختياراته). */
export function setMode(on) {
  state = { ...state, on: on === true };
  save();
}

/** تشغيل مقبضٍ بعينه أو إطفاؤه — والمشتغلُ هو الأصل فلا يُخزَّن إلا المطفأ. */
export function set(key, on) {
  if (!(key in KNOBS)) return;
  const next = { ...state };
  if (on === false) next[key] = false;
  else delete next[key];
  state = next;
  save();
}

